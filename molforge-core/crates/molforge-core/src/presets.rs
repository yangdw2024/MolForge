pub fn build_preset(name: &str) -> Option<Molecule> {
    match name.trim().to_ascii_lowercase().as_str() {
        "caffeine" => Some(caffeine()),
        "benzene" => Some(benzene()),
        "water" => Some(water()),
        "methane" => Some(methane()),
        "ethanol" => Some(ethanol()),
        "aspirin" => Some(aspirin()),
        _ => None,
    }
}

fn from_spec(name: &str, atoms: &[(u8, [f64; 3])], bonds: &[(usize, usize, u8)]) -> Molecule {
    let mut mol = Molecule::new(name);
    let mut ids = Vec::with_capacity(atoms.len());
    for &(z, pos) in atoms {
        let a = mol.alloc_atom(z, pos, [pos[0], pos[1]]);
        ids.push(a.id);
        mol.atoms.push(a);
    }
    mol.reindex();
    for &(ia, ib, ord) in bonds {
        let b = mol.alloc_bond(ids[ia], ids[ib], ord, false);
        mol.bonds.push(b);
    }
    mol.has_3d = true;
    mol.has_2d = true;
    mol
}

