fn benzene() -> Molecule {
    let mut atoms = Vec::with_capacity(12);
    let mut bonds = Vec::with_capacity(12);
    let rc = 1.39;
    let rh = 2.47;
    for i in 0..6 {
        let th = std::f64::consts::PI * 2.0 * (i as f64) / 6.0;
        atoms.push((6, [rc * th.cos(), rc * th.sin(), 0.0]));
    }
    for i in 0..6 {
        let th = std::f64::consts::PI * 2.0 * (i as f64) / 6.0;
        atoms.push((1, [rh * th.cos(), rh * th.sin(), 0.0]));
    }
    for i in 0..6 {
        bonds.push((i, (i + 1) % 6, if i % 2 == 0 { 2 } else { 1 }));
        bonds.push((i, i + 6, 1));
    }
    from_spec("Benzene", &atoms, &bonds)
}

