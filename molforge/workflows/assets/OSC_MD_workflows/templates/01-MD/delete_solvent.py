import random

def change_atom_part(line:str, new_index:int):
    atom_part = line[:11]
    new_atom_part = atom_part.replace(atom_part[6:], '{:>5}'.format(new_index))
    return line.replace(atom_part, new_atom_part)

def change_atom_part2(line:str, new_index:int):
    atom_part = line[13:20]
    new_atom_part = atom_part.replace(atom_part[2:], '{:>5}'.format(new_index))
    return line.replace(atom_part, new_atom_part)

def change_mol_part(line:str, new_index:int):
    mol_part = line[17:26]
    new_mol_part = mol_part.replace(mol_part[5:9], '{:>4}'.format(new_index))
    return line.replace(mol_part, new_mol_part)

def change_mol_part2(line:str, new_index:int):
    mol_part = line[:9]
    new_mol_part = mol_part.replace(mol_part[:5], '{:>5}'.format(new_index))
    return line.replace(mol_part, new_mol_part)

def main(structure_file_name:str, new_structure_file_name:str, 
         solvent_mol_name:str, delet_mol_num:int): 
    # read origin file 
    origin_file = open(structure_file_name)
    filelines = origin_file.readlines()
    origin_file.close()

    # read&get atom, mol, line indices
    solvent_atom_indices = []
    solvent_atom_mol_indices = []
    solvent_atom_line_indices = []
    for i, line in enumerate(filelines):
        if solvent_mol_name in line:
            solvent_atom_indices.append(int(line.split()[1]))
            solvent_atom_mol_indices.append(int(line[22:26]))
            solvent_atom_line_indices.append(i)
    solvent_atom_num = len(solvent_atom_indices)
    solvent_mol_num = solvent_atom_mol_indices[-1]

    # check
    #print(solvent_atom_num, solvent_mol_num, solvent_atom_num%solvent_mol_num)
    assert solvent_atom_num%solvent_mol_num == 0, \
    'Non-consistent solvent molecule atom number!'

    # calc delete/left mol indices
    all_mol_indices = [i for i in range(1, solvent_mol_num+1)]
    delet_mol_indices = random.sample(all_mol_indices, delet_mol_num)
    delet_mol_indices.sort()
    print('deleted mol indices:', delet_mol_indices)
    left_mol_origin_indices = list(set(all_mol_indices)-set(delet_mol_indices))
    left_mol_origin_indices.sort()

    # calc left lines' indices
    delet_lines_indices = []
    for i, mol_index in enumerate(solvent_atom_mol_indices):
        if mol_index in delet_mol_indices:
            delet_lines_indices.append(solvent_atom_line_indices[i])
    #print(delet_lines_indices)
    left_lines_indices = list(set([x for x in range(len(filelines))])-set(delet_lines_indices))
    left_lines_indices.sort()
#    print(delet_lines_indices)

    # change nol&atom indices
    new_file_lines = filelines.copy()
    new_atom_index = solvent_atom_indices[0]
    for i, line in enumerate(filelines):
        if solvent_mol_name in line:
            mol_index = int(line[22:26])
            if mol_index in delet_mol_indices: continue
            new_atom_index += 1
            new_mol_index = left_mol_origin_indices.index(mol_index)+1
            new_file_line = change_mol_part(line, new_mol_index)
            new_file_lines[i] = change_atom_part(new_file_line, new_atom_index)    

    # calc left lines' indices
    delet_lines_indices = []
    for i, mol_index in enumerate(solvent_atom_mol_indices):
        if mol_index in delet_mol_indices:
            delet_lines_indices.append(solvent_atom_line_indices[i])
    #print(delet_lines_indices)
    left_lines_indices = list(set([x for x in range(len(filelines))])-set(delet_lines_indices))
    left_lines_indices.sort()
    
    # generate new file contents 
    new_file_lines = [new_file_lines[i] for i in left_lines_indices]

    # write new file
    new_file = open(new_structure_file_name, 'w')
    new_file.writelines(new_file_lines)
    new_file.close()
    
    
