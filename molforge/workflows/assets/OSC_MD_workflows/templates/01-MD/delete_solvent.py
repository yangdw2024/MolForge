def change_complex_top(delet_mol_num, line_num):
    iline=line_num-1
    with open('complex.top','r') as file:
        data = file.readlines()
        keyline = data[iline].strip().split()
        origin_num = int(keyline[-1])
        new_num = origin_num-delet_mol_num
        data[iline]=keyline[0]+' {} \n'.format(new_num)
    with open('complex.top','w') as file:
        file.writelines(data)
    
    
