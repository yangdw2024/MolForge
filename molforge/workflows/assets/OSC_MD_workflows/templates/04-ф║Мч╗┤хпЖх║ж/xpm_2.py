import numpy as np
import matplotlib.pyplot as plt
import matplotlib.colors as cols
import sys

#运行方式python xpm_2.py x.xpm y.xpm
plt.rcParams['font.size'] = 32
#plt.rcParams['axes.linewidth'] = 2
plt.rcParams['font.family'] = 'Times New Roman'

def Read_XPM(fname):
    color, x, y, arr, value_list = {}, [], [], [], []
    title, legend, xlabel, ylabel = '', '', '', ''
    color_map = {'Coil': (1, 1, 1), 'B-Sheet': (1, 0, 0), 'B-Bridge': (0, 0, 0), 'Bend': (0, 1, 0), 
                 'Turn': (1, 1, 0), 'A-Helix': (0, 0, 1), '5-Helix': (0.7, 0.3, 0.8), '3-Helix': (0.5, 0.5, 0.5), 
                 'Chain': (0, 0.5, 0.5)}
    with open(fname, 'r') as f:
        line = f.readline().rstrip('\n')
        while line:
            if 'title' in line:
                title  = line.split('"')[1] 
            elif 'legend' in line:
                legend = line.split('"')[1]
            elif 'x-label' in line:
                xlabel = line.split('"')[1]
            elif 'y-label' in line:
                ylabel = line.split('"')[1]
            # 矩阵维度dim[0]*dim[1], nframe * nres
            elif 'static char' in line:
                dim = np.array(f.readline().split('"')[1].split(), dtype=int)
                for i in range(dim[2]):    
                    temp = f.readline().rstrip('\n')
                    value = temp.split('"')[-2]
                    if value == "Chain_Separator": 
                        value = "Chain"
                    value_list.append(value)
                    if 'Secondary' not in title:
                        color[temp[1]] = float(value) if 'Hydrogen' not in ylabel else 0 if value == 'None' else 1
                    else:
                        color[temp[1]] = i
            # 坐标值
            elif 'x-axis' in line:
                x.extend(line.split()[2:-1])
            elif 'y-axis' in line:
                y.extend(line.split()[2:-1])
            elif line[0] == '"' and line[dim[0]+1] == '"':
                temp = [color[line[j]] for j in range(1, dim[0]+1)]
                arr.append(temp)
            line = f.readline().rstrip('\n')
        # 必须按行反向列表，因为xpm中的数据默认是反向的，即最后一行数据才是开始值
        arr.reverse()
    # 处理一下维度，因为有的xpm文件坐标个数会大于下面的矩阵维度dim[0](如gmx sham)
    if len(x) > dim[0]:
        x.pop()
        y.pop()
    
    return title, legend, xlabel, ylabel, x, y, np.array(arr, dtype=float), value_list, color_map

def Plot_XPM(file1, file2):
    title1, legend1, xlabel1, ylabel1, x1, y1, arr1, value_list1, color_map1 = Read_XPM(file1)
    title2, legend2, xlabel2, ylabel2, x2, y2, arr2, value_list2, color_map2 = Read_XPM(file2)

    # 假设两个文件的x和y轴标签相同
    x = np.array(x1, dtype=float)
    y = np.array(y1, dtype=float)
    X, Y = np.meshgrid(x, y)

    # 绘图
    plt.figure(figsize=(8, 6))
    
    # 绘制第一个文件的数据
    Z1 = arr1
    h1 = plt.contourf(X, Y, Z1, np.linspace(0, 300, 205), cmap="Greens", vmin=0, vmax=280, alpha=0.5)
    
    # 绘制第二个文件的数据
    Z2 = arr2
    h2 = plt.contourf(X, Y, Z2, np.linspace(0, 300, 205), cmap="Greens", vmin=0, vmax=280, alpha=0.5)

    cb = plt.colorbar(h1, ticks=np.linspace(0, 300, 5))
    cb.ax.tick_params(labelsize=12)
    cb.set_label(legend1, fontsize=18)

    plt.title(title1, fontsize=18)
    plt.xlabel(xlabel1, fontsize=18)
    plt.ylabel(ylabel1, fontsize=18)
    plt.xticks(fontsize=15)
    plt.yticks(fontsize=15)
    plt.xlim([np.min(x), np.max(x)])
    plt.ylim([np.min(y), np.max(y)])
    plt.savefig(file1.split('.')[0] + '_' + file2.split('.')[0] + '.png', dpi=300)
    # 将坐标轴加粗显示
    plt.gca().spines['bottom'].set_linewidth(15)
    plt.gca().spines['left'].set_linewidth(15)

def Help(argv):
    print('->>Description:\nThis program can read most common xpm file generated by gromacs tools, then plot figure')
    print('Usage:\n\t./%s  xxx.xpm yyy.xpm\n' % (argv))
    exit(-1)

if __name__ == '__main__':
    if len(sys.argv) < 3:
        Help(sys.argv[0])
    Plot_XPM(sys.argv[1], sys.argv[2])
